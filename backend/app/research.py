from datetime import datetime, timezone


def generate_demo_report(topic: str) -> tuple[str, str]:
    """Generate a sample report without claiming live chain research."""
    title = f"Onchain Intelligence Brief: {topic[:90]}"
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    body = f"""# {title}

> **DEMO DATA NOTICE:** This report was generated in synthetic demo mode on {generated_at}. It does not contain live blockchain queries, verified market metrics, or investment advice.

## Research question
{topic}

## What this business would investigate
1. **Network activity:** transaction count, active addresses, fees, and changes across comparable time windows.
2. **Application traction:** usage by protocol, returning users, retention, and concentration across applications.
3. **Capital movement:** liquidity depth, bridge flows, stablecoin activity, and large changes in TVL.
4. **Developer momentum:** deployments, repository activity, releases, and ecosystem integrations.
5. **Risk signals:** unusual concentration, liquidity fragmentation, contract incidents, and dependence on a small number of applications.

## Demo findings
This build uses a demonstration workflow rather than live chain data. No numerical claims are made because no live source has been queried. In a connected research run, each finding would include its source, query window, retrieval timestamp, and a reproducible link or query.

## Decision summary
A production report should separate observed facts from interpretation, compare activity across consistent time windows, and flag missing or low-confidence data. Activity alone should not be treated as proof of product-market fit or as a trade recommendation.

## Sources and verification
- Live sources queried: **none (demo mode)**
- Data retrieval timestamp: {generated_at}
- Report mode: synthetic_demo
- Next step: connect approved public data sources and persist source records before labelling a report as live research.

---
Generated by the Autonomous Onchain Intelligence Business demo.
"""
    return title, body
