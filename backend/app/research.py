def generate_demo_report(topic: str) -> tuple[str, str]:
    """Generate a clearly labelled sample report without claiming live research."""
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    title = f"MERIDIAN Demo Research Brief: {topic[:75]}"
    body = f"""# {title}

> **SYNTHETIC DEMO:** Generated on {generated_at}. This report contains no live blockchain queries, verified project metrics, or investment advice.

## Research question
{topic}

## What a full research run should verify
1. Chain activity: transactions, active addresses, fees, and contract deployments.
2. DeFi adoption: chain TVL, protocol-level TVL, stablecoin liquidity, and category-level methodology.
3. NEAR AI: model catalogue, inference API, privacy tier, and verification capabilities.
4. NEAR Intents: supported routes, quote quality, execution volume, and settlement outcomes.
5. Business potential: real users, repeat usage, transaction costs, monetisation, and operational risks.

## Findings
No findings are asserted in synthetic demo mode. A live report must include the underlying source, retrieval timestamp, measurement period, and a data-quality note for each material metric.

## Sources
- Live sources queried: none
- Report mode: synthetic_demo

---
Generated by MERIDIAN.
"""
    return title, body


def _usd(value: float | None) -> str:
    if value is None:
        return "not available"
    if value >= 1_000_000_000:
        return "$" + format(value / 1_000_000_000, ".2f") + "B"
    if value >= 1_000_000:
        return "$" + format(value / 1_000_000, ".2f") + "M"
    return "$" + format(value, ",.2f")


def _metric_change(value: float | None) -> str:
    return "not available" if value is None else format(value, "+.2f") + "%"


def _protocol_lines(context: dict) -> str:
    rows = context.get("top_protocols") or []
    if not rows:
        return "- No eligible protocol rows passed category and value-consistency checks."
    return "\n".join(
        "- **{name}** ({category}): {value} chain-specific TVL".format(
            name=row["name"],
            category=row["category"],
            value=_usd(row["chain_tvl_usd"]),
        )
        for row in rows
    )


def _excluded_protocol_lines(context: dict) -> str:
    rows = context.get("excluded_protocols") or []
    if not rows:
        return "- No protocol rows needed to be excluded by the applied filters."
    return "\n".join(
        "- **{name}** ({category}): {reason}".format(
            name=row.get("name", "Unknown"),
            category=row.get("category", "Uncategorised"),
            reason=row.get("reason", "Excluded by data-quality filter."),
        )
        for row in rows[:12]
    )


def _activity_summary(activity: dict) -> str:
    lines = []
    for key, title in (
        ("transaction_stats", "Daily transactions"),
        ("address_stats", "Daily active/unique addresses"),
    ):
        metric = activity.get(key) or {"status": "unavailable"}
        if metric.get("status") != "available":
            lines.append(f"- **{title}:** unavailable ({metric.get('reason', 'source did not return a recognised daily metric')})")
            continue
        change = metric.get("last_7d_vs_previous_7d_percent")
        change_text = "not available" if change is None else format(change, "+.2f") + "%"
        lines.append(
            f"- **{title}:** {metric.get('latest_day_value'):,.0f} on {metric.get('latest_day')}; "
            f"{metric.get('last_7d_total'):,.0f} across {metric.get('last_7d_days')} reported days; "
            f"7-day change vs previous 7 days: {change_text}."
        )
    return "\n".join(lines)


def _official_metrics_lines(official: dict) -> str:
    metrics = official.get("official_hub_metrics") or []
    if not metrics:
        return (
            "- The official analytics hub was checked, but no headline metrics could be reliably extracted. "
            "Use the linked dashboards for current activity analysis."
        )
    labels = {
        "daily_transactions": "Daily transactions",
        "monthly_active_users": "Monthly active users",
        "tps_headline": "Transactions per second headline",
        "stablecoin_supply": "Stablecoin supply",
        "ecosystem_funding": "Total funding raised",
    }
    lines = []
    for item in metrics:
        label = labels.get(item["metric"], item["metric"].replace("_", " ").title())
        lines.append(
            f"- **{label}:** {item['publisher_displayed_value']} "
            "(NEAR-published headline; metric definition and data cut-off are not shown on the page)."
        )
    return "\n".join(lines)


def _intents_summary(official: dict) -> str:
    metric = official.get("intents_home_metric")
    if not metric:
        headline = "- NEAR Intents public headline volume was not extractable during this research run."
    else:
        headline = (
            "- NEAR Intents currently displays **{volume} all-time volume across {chains} chains**. "
            "This is publisher-reported; MERIDIAN has not independently reconstructed it from transaction records."
        ).format(
            volume=metric["all_time_volume_displayed"],
            chains=metric["chains_displayed"],
        )
    explorer = official.get("near_intents_explorer") or {}
    if explorer.get("status") == "jwt_required":
        detail = (
            "- Transaction-level Explorer API analytics: **not queried** because the official Explorer API "
            "requires a partner JWT. No transaction count or execution volume is inferred from the homepage headline."
        )
    else:
        detail = (
            "- A partner JWT is present, but the Explorer API has not yet been queried by this report version."
        )
    return headline + "\n" + detail


async def generate_near_ai_analysis(topic: str, context: dict) -> tuple[str | None, dict]:
    api_key = os.getenv("NEAR_AI_API_KEY", "").strip()
    if not api_key:
        return None, {"status": "not_configured", "provider": "near_ai_cloud"}

    base_url = os.getenv("NEAR_AI_BASE_URL", "https://cloud-api.near.ai/v1").rstrip("/")
    model = os.getenv("NEAR_AI_MODEL", NEAR_AI_DEFAULT_MODEL)
    payload = {
        "model": model,
        "temperature": 0.15,
        "max_tokens": 2200,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You are MERIDIAN's evidence-led onchain research analyst. Use only the supplied "
                    "research context. Never invent a metric, project capability, source, event, date, "
                    "or adoption claim. Keep publisher-reported figures separate from independently "
                    "queried data. Explain missing data and methodological conflicts. Never add protocol "
                    "TVL rows together unless the source explicitly guarantees they are non-overlapping. "
                    "Separate verified observations, interpretation, opportunities, and risks. Cite the "
                    "provided source names inline. If evidence is insufficient, say so plainly."
                ),
            },
            {
                "role": "user",
                "content": (
                    "Research question: " + topic + "\n\n"
                    "Verified and publisher-reported source context (JSON):\n"
                    + json.dumps(context, sort_keys=True, ensure_ascii=False)
                    + "\n\nWrite an executive analysis with: key findings; what the evidence says "
                    "about real adoption; NEAR AI and agent infrastructure; NEAR Intents and payments; "
                    "commercial opportunities; risks and open questions; and the next data checks. "
                    "Do not state unavailable metrics as facts."
                ),
            },
        ],
    }
    timeout = httpx.Timeout(75.0, connect=10.0)
    try:
        async with httpx.AsyncClient(timeout=timeout) as client:
            response = await client.post(
                base_url + "/chat/completions",
                headers={
                    "Authorization": "Bearer " + api_key,
                    "Content-Type": "application/json",
                },
                json=payload,
            )
            response.raise_for_status()
            result = response.json()
        content = result["choices"][0]["message"]["content"]
        if not isinstance(content, str) or not content.strip():
            raise ValueError("NEAR AI Cloud returned an empty analysis.")
        return content.strip(), {
            "status": "completed",
            "provider": "near_ai_cloud",
            "model": result.get("model", model),
            "usage": result.get("usage"),
        }
    except (httpx.HTTPError, ValueError, KeyError, IndexError, TypeError) as exc:
        return None, {
            "status": "unavailable_fallback_used",
            "provider": "near_ai_cloud",
            "model": model,
            "error": str(exc)[:240],
        }


async def generate_live_report(
    topic: str, default_chain: str = "Near"
) -> tuple[str, str, str, dict]:
    chain_task = collect_defillama_context(topic, default_chain)
    activity_task = collect_nearblocks_activity()
    official_task = collect_official_near_context()

    chain_context = await chain_task
    activity_result, official_result = await __import__("asyncio").gather(
        activity_task, official_task, return_exceptions=True
    )
    activity = (
        activity_result if isinstance(activity_result, dict)
        else {
            "status": "unavailable",
            "transaction_stats": {"status": "unavailable", "reason": "NearBlocks source request failed."},
            "address_stats": {"status": "unavailable", "reason": "NearBlocks source request failed."},
            "sources": ["https://api.nearblocks.io/api-docs/ui/"],
        }
    )
    official = (
        official_result if isinstance(official_result, dict)
        else {
            "official_hub_metrics": [],
            "intents_home_metric": None,
            "near_ai_documented_facts": [],
            "near_intents_documented_facts": [],
            "near_intents_explorer": {"status": "jwt_required"},
            "sources": [
                "https://www.near.org/research-analytics",
                "https://intents.near.org/",
                "https://docs.near.ai/llms.txt",
                "https://docs.near-intents.org/llms.txt",
            ],
        }
    )

    research_context = {
        "defillama": chain_context,
        "nearblocks": activity,
        "official_near": official,
    }
    ai_analysis, ai_meta = await generate_near_ai_analysis(topic, research_context)
    data_mode = "near_ai_live" if ai_analysis else "defillama_live"

    chain = chain_context["chain"]
    retrieved = datetime.now(timezone.utc).isoformat()
    history_age = chain_context.get("history_age_hours")
    history_age_text = "not available" if history_age is None else f"{history_age:.1f} hours"
    ai_status = ai_meta["status"]
    if ai_analysis:
        analysis = ai_analysis
    else:
        analysis = (
            "NEAR has two relevant infrastructure pillars documented in the official sources: "
            "NEAR AI Cloud provides an OpenAI-compatible inference API with model-dependent privacy tiers, "
            "while NEAR Intents 1Click provides an intent-based cross-chain quote, deposit, and execution flow. "
            "The public sources retrieved for this report do not establish that MERIDIAN has processed customer "
            "payments or that its target AI-agent ecosystem has a particular number of active agents. "
            "Network activity is reported separately below where NearBlocks returned recognisable daily metrics. "
            "The official ecosystem and Intents homepage figures are publisher-reported, not independently "
            "reconstructed. These observations support building a research-and-settlement business, but do not "
            "by themselves prove product demand or paying customer adoption."
        )

    quality_warnings = chain_context.get("quality_warnings") or []
    if activity.get("status") != "available":
        quality_warnings.append(
            "NearBlocks daily activity metrics were unavailable or did not match a recognised response field."
        )
    if not official.get("near_intents_documented_facts"):
        quality_warnings.append("Official NEAR Intents documentation could not be retrieved during this run.")
    if ai_status != "completed":
        quality_warnings.append("NEAR AI Cloud analysis did not run; deterministic source summary used.")

    excluded_count = chain_context.get("excluded_protocol_count", 0)
    excluded_section = _excluded_protocol_lines(chain_context)
    protocol_sum_note = (
        "Protocol-level values are individual reported measurements and may overlap. They are not added "
        "together to recreate chain TVL."
    )
    sources = list(dict.fromkeys(
        (chain_context.get("sources") or [])
        + (activity.get("sources") or [])
        + (official.get("sources") or [])
    ))
    sources_markdown = "\n".join("- " + source for source in sources)
    warning_markdown = (
        "\n".join("- " + warning for warning in quality_warnings)
        if quality_warnings else "- No automated data-quality warnings were raised."
    )
    ai_status_note = (
        f"completed with model {ai_meta.get('model', 'unknown')}"
        if ai_status == "completed"
        else "not configured" if ai_status == "not_configured"
        else "unavailable; deterministic fallback used"
    )

    title = "MERIDIAN NEAR Ecosystem Intelligence: " + chain + " — " + topic[:55]
    body = f"""# {title}

> **Research retrieved:** {retrieved}. This report separates independently queried data from publisher-displayed metrics and product-documentation facts. Publisher headlines are not treated as independent onchain measurements.

## Research question
{topic}

## Executive analysis
{analysis}

## 1. DeFi capital: chain TVL
- **Chain:** {chain}
- **Current chain TVL:** {_usd(chain_context.get("current_tvl_usd"))}
- **Historical change (7 days):** {_metric_change(chain_context.get("change_7d_percent"))}
- **Historical change (30 days):** {_metric_change(chain_context.get("change_30d_percent"))}
- **Historical observations:** {chain_context.get("history_points", 0)}
- **Latest historical observation age:** {history_age_text}
- **Retrieved:** {chain_context.get("retrieved_at", "not available")}

### Eligible protocol rows
{_protocol_lines(chain_context)}

{protocol_sum_note}

### Excluded or inconsistent rows
{excluded_section}

DefiLlama's chain-TVL methodology excludes bridge TVL and liquid-staking TVL from chain totals by default. CEX assets are not a chain DeFi-TVL contribution. A protocol is also excluded here when its reported chain-specific value exceeds the chain-wide figure by more than 5%, or when DefiLlama flags it as double-counted.

## 2. Network adoption and usage
{_activity_summary(activity)}

NearBlocks data is a third-party indexed source. Its public API documentation identifies daily transaction and address statistics endpoints; MERIDIAN reports only numeric fields it can recognise in the response. NearBlocks attribution: Powered by NearBlocks.io APIs.

## 3. NEAR ecosystem metrics hub
{_official_metrics_lines(official)}

These are publisher-displayed headline values from NEAR's research and analytics page. The page view retrieved does not provide the underlying query definitions or a data cut-off alongside each headline, so these values are not used as independent proof of active users, transaction growth, or economic value.

## 4. NEAR AI and agent infrastructure
{chr(10).join("- " + item for item in (official.get("near_ai_documented_facts") or ["Official NEAR AI Cloud documentation could not be retrieved in this run."]))}

The current model catalogue distinguishes Confidential TEE, third-party Confidential TEE, and Incognito tiers. A report must not imply that every model gets the same hardware isolation or verification guarantees. NEAR AI Cloud model analysis in this report: **{ai_status_note}**.

## 5. NEAR Intents and autonomous payments
{_intents_summary(official)}

{chr(10).join("- " + item for item in (official.get("near_intents_documented_facts") or ["Official NEAR Intents integration documentation could not be retrieved in this run."]))}

**MERIDIAN integration boundary:** the product has only a community Tidepool dry-quote preview. It has not created a deposit address, accepted customer payment, submitted a transaction, or settled a NEAR Intents swap. The official NEAR Intents 1Click API has no testnet version; never describe Tidepool as an official NEAR testnet.

## 6. Commercial opportunities
- **Paid research:** package source-backed chain and ecosystem analysis into reports with clear freshness, evidence, and methodology.
- **Agent inference:** use NEAR AI Cloud for evidence synthesis where a configured model tier meets the data-handling requirements.
- **Intent-based settlement:** a future payment adapter can use NEAR Intents for supported cross-chain payments, but only after an owner-approved mainnet flow, quote verification, wallet custody, settlement monitoring, and refund handling are implemented.
- **Contributor economics:** automate accounting only after payment settlement is proven; until then revenue shares remain projections.

## 7. Risks and open questions
- TVL is a capital-deposit measure, not a count of customers, transactions, fees, or protocol revenue.
- Protocol-level TVL rows can overlap; they must not be summed unless the data provider confirms they are non-overlapping.
- Official ecosystem headline figures have publisher-defined methodology and a separate data cut-off that must be checked before investment-grade use.
- NEAR Intents is mainnet-only according to its official quickstart. Mainnet tests risk real assets.
- NEAR AI privacy guarantees depend on the selected model tier.
- A live source snapshot does not establish repeat customers, revenue, retention, or willingness to pay for MERIDIAN's reports.

## 8. Data quality checks
{warning_markdown}

## Sources
{sources_markdown}

- Report mode: {data_mode}
- NEAR AI Cloud analysis: {ai_status_note}
- Payment state: unpaid; no customer funds received
- Onchain transaction state: none initiated
"""
    metadata = {
        "provider": "defillama+nearblocks+near_official_sources",
        "chain": chain,
        "source_urls": sources,
        "data_mode": data_mode,
        "retrieved_at": retrieved,
        "nearblocks_status": activity.get("status"),
        "near_ai": ai_meta,
        "official_near": {
            "hub_metric_count": len(official.get("official_hub_metrics") or []),
            "intents_metric_available": bool(official.get("intents_home_metric")),
            "intents_explorer_status": (official.get("near_intents_explorer") or {}).get("status"),
        },
        "quality_warning_count": len(quality_warnings),
        "excluded_protocol_count": excluded_count,
    }
    return title, body, data_mode, metadata


async def generate_report(topic: str, rules: dict) -> tuple[str, str, str, dict]:
    mode = (rules.get("research") or {}).get("mode", "demo")
    if mode != "live":
        title, body = generate_demo_report(topic)
        return title, body, "synthetic_demo", {
            "provider": "synthetic_demo",
            "source_urls": [],
            "data_mode": "synthetic_demo",
        }
    default_chain = (rules.get("research") or {}).get("default_chain", "Near")
    return await generate_live_report(topic, default_chain)
