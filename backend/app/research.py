from __future__ import annotations

import asyncio
import json
import os
from datetime import datetime, timezone
from urllib.parse import quote

import httpx


DEFILLAMA_BASE = "https://api.llama.fi"
DEFAULT_NEAR_AI_BASE = "https://cloud-api.near.ai/v1"


class ResearchSourceError(Exception):
    pass


def generate_demo_report(topic: str) -> tuple[str, str]:
    """Generate a sample report without claiming live chain research."""
    title = f"Onchain Intelligence Brief: {topic[:90]}"
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    body = f"""# {title}

> **DEMO DATA NOTICE:** This report was generated in synthetic demo mode on {generated_at}. It does not contain live blockchain queries, verified market metrics, or investment advice.

## Research question
{topic}

## What this business would investigate
1. **Network activity:** transaction count, active addresses, fees, and changes across comparable time windows.
2. **Application traction:** usage by protocol, returning users, retention, and concentration across applications.
3. **Capital movement:** liquidity depth, bridge flows, stablecoin activity, and large changes in TVL.
4. **Developer momentum:** deployments, repository activity, releases, and ecosystem integrations.
5. **Risk signals:** unusual concentration, liquidity fragmentation, contract incidents, and dependence on a small number of applications.

## Demo findings
This build uses a demonstration workflow rather than live chain data. No numerical claims are made because no live source has been queried. In a connected research run, each finding would include its source, query window, retrieval timestamp, and a reproducible link or query.

## Decision summary
A production report should separate observed facts from interpretation, compare activity across consistent time windows, and flag missing or low-confidence data. Activity alone should not be treated as proof of product-market fit or as a trade recommendation.

## Sources and verification
- Live sources queried: **none (demo mode)**
- Data retrieval timestamp: {generated_at}
- Report mode: synthetic_demo
- Next step: connect approved public data sources and persist source records before labelling a report as live research.

---
Generated by the MERIDIAN research business demo.
"""
    return title, body


async def collect_defillama_context(topic: str, default_chain: str = "Near") -> dict:
    """Collect live chain TVL and protocol data from DefiLlama's free public API."""
    timeout = httpx.Timeout(20.0, connect=8.0)
    headers = {"User-Agent": "MERIDIAN-Autonomous-Research/0.2"}
    async with httpx.AsyncClient(timeout=timeout, headers=headers) as client:
        try:
            chain_response = await client.get(DEFILLAMA_BASE + "/v2/chains")
            chain_response.raise_for_status()
            chains = chain_response.json()
            if not isinstance(chains, list):
                raise ResearchSourceError("DefiLlama returned an unexpected chain catalogue.")

            chain_names = [
                str(item.get("name", ""))
                for item in chains
                if isinstance(item, dict) and item.get("name")
            ]
            mentioned = [name for name in chain_names if name.lower() in topic.lower()]
            if mentioned:
                selected_name = sorted(mentioned, key=len, reverse=True)[0]
            else:
                selected_name = next((name for name in chain_names if name.lower() == default_chain.lower()), None)
            if not selected_name:
                raise ResearchSourceError(
                    "The requested chain was not found in DefiLlama's public chain catalogue."
                )

            chain_row = next(
                item for item in chains
                if str(item.get("name", "")).lower() == selected_name.lower()
            )
            history_url = DEFILLAMA_BASE + "/v2/historicalChainTvl/" + quote(selected_name, safe="")
            history_response, protocols_response = await asyncio.gather(
                client.get(history_url),
                client.get(DEFILLAMA_BASE + "/protocols"),
            )
            history_response.raise_for_status()
            protocols_response.raise_for_status()
            history = history_response.json()
            protocols = protocols_response.json()
        except ResearchSourceError:
            raise
        except (httpx.HTTPError, ValueError, TypeError) as exc:
            raise ResearchSourceError(
                "The live DefiLlama data source could not be reached or returned invalid data."
            ) from exc

    if not isinstance(history, list) or not history:
        raise ResearchSourceError("No historical chain TVL data was returned for " + selected_name + ".")
    if not isinstance(protocols, list):
        raise ResearchSourceError("DefiLlama returned an unexpected protocol catalogue.")

    history = [row for row in history if isinstance(row, dict) and row.get("tvl") is not None]
    history.sort(key=lambda row: int(row.get("date", 0)))
    if not history:
        raise ResearchSourceError("Historical TVL data was empty for " + selected_name + ".")

    latest = history[-1]
    latest_tvl = float(latest["tvl"])

    def change_from(days_ago: int) -> float | None:
        if len(history) <= days_ago:
            return None
        old_value = float(history[-(days_ago + 1)]["tvl"])
        if old_value <= 0:
            return None
        return round(((latest_tvl / old_value) - 1) * 100, 2)

    protocol_rows = []
    for protocol in protocols:
        if not isinstance(protocol, dict):
            continue
        chains_for_protocol = [
            str(name).lower() for name in (protocol.get("chains") or [])
        ]
        if selected_name.lower() not in chains_for_protocol:
            continue
        chain_tvls = protocol.get("chainTvls") or {}
        chain_value = None
        for key, value in chain_tvls.items():
            if str(key).lower() == selected_name.lower():
                try:
                    chain_value = float(value)
                except (TypeError, ValueError):
                    chain_value = None
                break
        if chain_value is None:
            continue
        protocol_rows.append(
            {
                "name": str(protocol.get("name") or "Unknown"),
                "category": str(protocol.get("category") or "Uncategorised"),
                "chain_tvl_usd": chain_value,
                "change_1d_percent": protocol.get("change_1d"),
                "change_7d_percent": protocol.get("change_7d"),
            }
        )

    protocol_rows.sort(key=lambda item: item["chain_tvl_usd"], reverse=True)
    retrieved_at = datetime.now(timezone.utc).isoformat()
    return {
        "chain": selected_name,
        "current_tvl_usd": latest_tvl,
        "catalog_tvl_usd": float(chain_row.get("tvl") or latest_tvl),
        "change_7d_percent": change_from(7),
        "change_30d_percent": change_from(30),
        "history_points": len(history),
        "top_protocols": protocol_rows[:5],
        "retrieved_at": retrieved_at,
        "sources": [
            DEFILLAMA_BASE + "/v2/chains",
            history_url,
            DEFILLAMA_BASE + "/protocols",
        ],
    }


def _usd(value: float) -> str:
    if value >= 1_000_000_000:
        return "$" + format(value / 1_000_000_000, ".2f") + "B"
    if value >= 1_000_000:
        return "$" + format(value / 1_000_000, ".2f") + "M"
    return "$" + format(value, ",.2f")


async def generate_near_ai_analysis(topic: str, context: dict) -> str | None:
    api_key = os.getenv("NEAR_AI_API_KEY", "").strip()
    if not api_key:
        return None

    base_url = os.getenv("NEAR_AI_BASE_URL", DEFAULT_NEAR_AI_BASE).rstrip("/")
    model = os.getenv("NEAR_AI_MODEL", "Qwen/Qwen3.8-27B")
    payload = {
        "model": model,
        "temperature": 0.2,
        "max_tokens": 1200,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You are an onchain research analyst. Analyse only the supplied data. "
                    "Never invent metrics, events, dates, protocol facts, or sources. "
                    "Separate measured facts from interpretation, call out missing data, "
                    "and do not make investment recommendations."
                ),
            },
            {
                "role": "user",
                "content": (
                    "Research question: " + topic + "\n\n"
                    "Verified source data collected for this report:\n"
                    + json.dumps(context, sort_keys=True)
                    + "\n\nWrite a concise analysis with findings, caveats, and what to investigate next."
                ),
            },
        ],
    }
    timeout = httpx.Timeout(60.0, connect=10.0)
    async with httpx.AsyncClient(timeout=timeout) as client:
        response = await client.post(
            base_url + "/chat/completions",
            headers={"Authorization": "Bearer " + api_key, "Content-Type": "application/json"},
            json=payload,
        )
        response.raise_for_status()
        result = response.json()

    try:
        content = result["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError) as exc:
        raise ResearchSourceError("NEAR AI Cloud returned an unexpected chat completion response.") from exc
    if not isinstance(content, str) or not content.strip():
        raise ResearchSourceError("NEAR AI Cloud returned an empty analysis.")
    return content.strip()


async def generate_live_report(topic: str, default_chain: str = "Near") -> tuple[str, str, str, dict]:
    context = await collect_defillama_context(topic, default_chain)
    ai_analysis = None
    ai_status = "not_configured"
    if os.getenv("NEAR_AI_API_KEY", "").strip():
        try:
            ai_analysis = await generate_near_ai_analysis(topic, context)
            ai_status = "completed"
        except (httpx.HTTPError, ResearchSourceError, ValueError):
            ai_status = "unavailable_fallback_used"

    chain = context["chain"]
    title = "MERIDIAN Onchain Intelligence Brief: " + chain + " — " + topic[:65]
    retrieved = context["retrieved_at"]
    change_7d = (
        "not available" if context["change_7d_percent"] is None
        else format(context["change_7d_percent"], "+.2f") + "%"
    )
    change_30d = (
        "not available" if context["change_30d_percent"] is None
        else format(context["change_30d_percent"], "+.2f") + "%"
    )
    protocol_lines = []
    for protocol in context["top_protocols"]:
        protocol_lines.append(
            "- **" + protocol["name"] + "** (" + protocol["category"] + "): "
            + _usd(protocol["chain_tvl_usd"]) + " chain TVL"
        )
    if not protocol_lines:
        protocol_lines = ["- No protocol-level chain TVL records were available in the returned catalogue."]

    if ai_analysis:
        analysis = ai_analysis
        data_mode = "near_ai_live"
    else:
        analysis = (
            "The live TVL snapshot is available, but no NEAR AI Cloud analysis was completed. "
            "This report therefore presents measured source data and a limited deterministic summary. "
            "It does not infer user activity, transaction count, revenue, or developer adoption from TVL alone."
        )
        data_mode = "defillama_live"

    source_lines = "\n".join("- " + source for source in context["sources"])
    body = f"""# {title}

> **LIVE SOURCE DATA:** Chain TVL and protocol data retrieved from DefiLlama at {retrieved}. TVL is a capital-deposit metric, not a direct measure of users, transactions, revenue, or network health.

## Research question
{topic}

## Measured snapshot
- **Chain:** {chain}
- **Current chain TVL:** {_usd(context["current_tvl_usd"])}
- **Historical change (7 days):** {change_7d}
- **Historical change (30 days):** {change_30d}
- **Historical samples:** {context["history_points"]}
- **Top protocol rows:** {len(context["top_protocols"])}

## Leading protocol TVL
{chr(10).join(protocol_lines)}

## Analysis
{analysis}

## Method and limitations
- Chain-level TVL and historical series are sourced from DefiLlama's public API.
- Protocol rows are filtered to the selected chain and ranked by chain-specific TVL where available.
- TVL can move because of token prices, deposits, withdrawals, reclassifications, or methodology changes.
- This report does not include transaction counts, unique users, security audits, or protocol revenue unless separately sourced.
- This report is informational and is not investment advice.

## Sources
{source_lines}

- Retrieved at: {retrieved}
- Research mode: {data_mode}
- NEAR AI Cloud analysis: {ai_status}
"""
    metadata = {
        "provider": "defillama",
        "chain": chain,
        "source_urls": context["sources"],
        "ai_provider": "near_ai_cloud" if ai_analysis else None,
        "ai_status": ai_status,
        "data_mode": data_mode,
        "retrieved_at": retrieved,
    }
    return title, body, data_mode, metadata


async def generate_report(topic: str, rules: dict) -> tuple[str, str, str, dict]:
    mode = (rules.get("research") or {}).get("mode", "demo")
    if mode != "live":
        title, body = generate_demo_report(topic)
        return title, body, "synthetic_demo", {
            "provider": "synthetic_demo",
            "source_urls": [],
            "data_mode": "synthetic_demo",
        }
    default_chain = (rules.get("research") or {}).get("default_chain", "Near")
    return await generate_live_report(topic, default_chain)
